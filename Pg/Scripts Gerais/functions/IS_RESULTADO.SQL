CREATE OR REPLACE FUNCTION IS_RESULTADO(V_POSTO       IN INT,
                                        V_ATENDIMENTO IN INT,
                                        V_CORREL      IN INT) RETURN INT IS
 DECLARE QT_RESULTADOS INT; 
BEGIN

    SELECT COUNT(1) INTO QT_RESULTADOS FROM RESULTADOS_ATUAL
     WHERE POSTO = V_POSTO AND ATENDIMENTO = V_ATENDIMENTO AND CORREL = V_CORREL;

    RETURN QT_RESULTADOS;
END IS_RESULTADO;
$$ LANGUAGE plpgsql;                                      
