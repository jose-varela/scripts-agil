CREATE OR REPLACE FUNCTION GET_MAX_ORDEM_CORRELACAO(V_POSTO       IN INT,
                                                    V_ATENDIMENTO IN INT) RETURN INT IS
 DECLARE RESULT INT;
BEGIN

     SELECT COALESCE(MAX(EC.ORDEM_CORRELACAO),0) INTO RESULT FROM EXAMES_CORRELACIONADOS EC
      WHERE EC.POSTO = V_POSTO
        AND EC.ATENDIMENTO = V_ATENDIMENTO;
    RETURN(RESULT);
END GET_MAX_ORDEM_CORRELACAO;
$$ LANGUAGE plpgsql;
