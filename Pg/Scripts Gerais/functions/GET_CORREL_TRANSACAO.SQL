CREATE OR REPLACE FUNCTION GET_CORREL_TRANSACAO(V_POSTO       IN INT,
                                                V_ATENDIMENTO IN INT) RETURN INT IS
 DECLARE RESULT INT;
BEGIN

     SELECT COALESCE(MAX(CORREL_TRANSACAO),0) INTO RESULT FROM TRANSACOES_TES
      WHERE POSTO = V_POSTO 
        AND ATENDIMENTO = V_ATENDIMENTO;

    RETURN(RESULT);
END GET_CORREL_TRANSACAO;
$$ LANGUAGE plpgsql;
