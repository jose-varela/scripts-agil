CREATE OR REPLACE FUNCTION IS_ATENDIMENTO(V_POSTO       IN INT,
                                          V_ATENDIMENTO IN INT) RETURN BOOLEAN IS
 DECLARE QT_ATENDIMENTOS INT; 
BEGIN

    SELECT COUNT(1) INTO QT_ATENDIMENTOS FROM ATENDIMENTOS
     WHERE POSTO = V_POSTO AND ATENDIMENTO = V_ATENDIMENTO;

    IF QT_ATENDIMENTOS = 0 THEN
       RETURN FALSE;
    ELSE
       RETURN TRUE;
    END IF;
END IS_ATENDIMENTO;
$$ LANGUAGE plpgsql;                                      
