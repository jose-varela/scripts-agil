CREATE OR REPLACE FUNCTION GET_CORREL_CORRECAO_GUIAS(V_ID_ATENDIMENTO IN INT) RETURN INT IS
 DECLARE RESULT INT;
BEGIN

     SELECT COALESCE(MAX(CORREL_CORRECAO),0) INTO RESULT FROM CORRECAO_GUIAS_ATENDIMENTOS
      WHERE ID_ATENDIMENTO = V_ID_ATENDIMENTO;

    RETURN(RESULT);
END GET_CORREL_CORRECAO_GUIAS;
$$ LANGUAGE plpgsql;
