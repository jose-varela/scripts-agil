CREATE OR REPLACE FUNCTION GET_VALOR_CH_TABELA(V_CONVENIO    IN INT,
                                               V_MNEMONICO   IN VARCHAR(4000)) RETURN INT IS
 DECLARE vVALOR_CH_TABELA DECIMAL(10,2);
vNOME_TABELA VARCHAR(30);
vSQL         VARCHAR(256);    BEGIN
--string que recebe o comando SQL dinâmico

     vSQL := 'SELECT DISTINCT ''TABELA'' || C.CATALOGO FROM CONVENIOS C WHERE C.CONVENIO = ' || V_CONVENIO;

     EXECUTE IMMEDIATE vSQL INTO vNOME_TABELA;

     vSQL := 'SELECT VALOR_CH FROM '|| vNOME_TABELA || ' WHERE MNEMONICO = ''' || V_MNEMONICO || '''';
	 
     EXECUTE IMMEDIATE vSQL INTO vVALOR_CH_TABELA;
	 
     RETURN(vVALOR_CH_TABELA);

END GET_VALOR_CH_TABELA;
$$ LANGUAGE plpgsql;
