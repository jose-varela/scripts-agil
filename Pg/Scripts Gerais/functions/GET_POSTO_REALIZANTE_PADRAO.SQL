CREATE OR REPLACE FUNCTION GET_POSTO_REALIZANTE_PADRAO(V_MNEMONICO   IN VARCHAR(1),
                                                       V_POSTO       IN INT) RETURN CHAR IS
 DECLARE RESULT CHAR;
BEGIN

     SELECT COALESCE(PADRAO,'N') INTO RESULT FROM POSTOS_PROCEDIMENTOS
      WHERE MNEMONICO = V_MNEMONICO
        AND POSTO = V_POSTO;

    RETURN(RESULT);
END GET_POSTO_REALIZANTE_PADRAO;
$$ LANGUAGE plpgsql;
