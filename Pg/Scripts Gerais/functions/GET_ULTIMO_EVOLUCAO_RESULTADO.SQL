CREATE OR REPLACE FUNCTION GET_ULTIMO_EVOLUCAO_RESULTADO(V_POSTO       IN INT,
                                                         V_ATENDIMENTO IN INT,
                                                         V_CORREL      IN INT) RETURN TIMESTAMP(0) IS
 DECLARE RESULT TIMESTAMP(0);
BEGIN

     SELECT MAX(ER.DATA_EVOLUCAO) INTO RESULT FROM EVOLUCAO_RESULTADOS ER
      WHERE ER.POSTO = V_POSTO
        AND ER.ATENDIMENTO = V_ATENDIMENTO
        AND ER.CORREL = V_CORREL;
    RETURN(RESULT);
END GET_ULTIMO_EVOLUCAO_RESULTADO;
$$ LANGUAGE plpgsql;
