CREATE OR REPLACE FUNCTION GET_MNEMONICO_DE_PARA(V_POSTO       IN INT,
                                                 V_ATENDIMENTO IN INT,
                                                 V_CORREL_DE   IN INT) RETURN VARCHAR(4000) IS
 DECLARE MNEMONICO_CORRELACIONADO VARCHAR(7); 
BEGIN

    SELECT E.MNEMONICO INTO MNEMONICO_CORRELACIONADO 
	  FROM EXAMES_CORRELACIONADOS EC, EXAMES E
     WHERE EC.POSTO = V_POSTO AND EC.ATENDIMENTO = V_ATENDIMENTO AND EC.CORREL_DE = V_CORREL_DE
	   AND E.POSTO = V_POSTO AND E.ATENDIMENTO = V_ATENDIMENTO AND E.CORREL = EC.CORREL_PARA;

    RETURN MNEMONICO_CORRELACIONADO;
    
END GET_MNEMONICO_DE_PARA;
$$ LANGUAGE plpgsql;                                      
