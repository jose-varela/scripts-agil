CREATE OR REPLACE FUNCTION GET_REGISTRO(V_POSTO IN INT, V_ATENDIMENTO IN INT) RETURN INT IS
 DECLARE RESULT INT;
BEGIN

     SELECT COALESCE(REGISTRO,-1) INTO RESULT FROM ATENDIMENTOS
      WHERE POSTO = V_POSTO AND ATENDIMENTO = V_ATENDIMENTO;

    RETURN(RESULT);
END GET_REGISTRO;
$$ LANGUAGE plpgsql;
