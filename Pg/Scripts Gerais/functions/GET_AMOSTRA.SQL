CREATE OR REPLACE FUNCTION GET_AMOSTRA(V_POSTO       IN INT,
                                       V_ATENDIMENTO IN INT,
                                       V_CORREL      IN INT) RETURN INT IS
 DECLARE RESULT INT;
BEGIN

     SELECT COALESCE(MAX(AMOSTRA),0) INTO RESULT FROM AMOSTRAS
      WHERE POSTO = V_POSTO 
        AND ATENDIMENTO = V_ATENDIMENTO 
        AND CORREL = V_CORREL;

    RETURN(RESULT);
END GET_AMOSTRA;
$$ LANGUAGE plpgsql;
