CREATE OR REPLACE FUNCTION GET_TIPO_ACORDO_TABELA(V_CONVENIO    IN INT,
                                                  V_MNEMONICO   IN VARCHAR(4000)) RETURN VARCHAR(4000) IS
 DECLARE vTIPO_ACORDO_TABELA VARCHAR(3);
vNOME_TABELA VARCHAR(30);
vSQL         VARCHAR(256);    BEGIN
--string que recebe o comando SQL dinâmico

     vSQL := 'SELECT DISTINCT ''TABELA'' || C.CATALOGO FROM CONVENIOS C WHERE C.CONVENIO = ' || V_CONVENIO;

     EXECUTE IMMEDIATE vSQL INTO vNOME_TABELA;

     vSQL := 'SELECT TIPO_ACORDO FROM '|| vNOME_TABELA || ' WHERE MNEMONICO = ''' || V_MNEMONICO || '''';
	 
     EXECUTE IMMEDIATE vSQL INTO vTIPO_ACORDO_TABELA;
	 
     RETURN(vTIPO_ACORDO_TABELA);

END GET_TIPO_ACORDO_TABELA;
$$ LANGUAGE plpgsql;
