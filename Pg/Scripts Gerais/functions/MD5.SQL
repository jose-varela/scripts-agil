CREATE OR REPLACE FUNCTION MD5 (VALOR VARCHAR(1)) RETURN VARCHAR(4000) IS
 DECLARE
V_INPUT VARCHAR(2000) = VALOR;
HEXKEY  VARCHAR(32)   = NULL;

BEGIN

     HEXKEY := RAWTOHEX(DBMS_OBFUSCATION_TOOLKIT.MD5(INPUT => UTL_RAW.CAST_TO_RAW(V_INPUT)));
     
     RETURN COALESCE(HEXKEY,'');
END;
$$ LANGUAGE plpgsql;
