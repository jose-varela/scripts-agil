CREATE OR REPLACE FUNCTION GET_MNEMONICOS(V_POSTO       IN INT,
                                          V_ATENDIMENTO IN INT) RETURN VARCHAR(4000) IS
 DECLARE MNEMONICOS VARCHAR(200);

    CURSOR CUR_MNEMONICOS IS
      SELECT MNEMONICO FROM EXAMES WHERE POSTO = V_POSTO AND ATENDIMENTO = V_ATENDIMENTO;

BEGIN


MNEMONICOS := '';

FOR MNEMONICOS_REC in CUR_MNEMONICOS
LOOP
    MNEMONICOS := MNEMONICOS || MNEMONICOS_REC.MNEMONICO || ' ';
END LOOP;

RETURN MNEMONICOS;

END;
$$ LANGUAGE plpgsql;
