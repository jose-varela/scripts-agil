CREATE OR REPLACE FUNCTION GET_NOME_TABELA(V_CONVENIO IN INT) RETURN VARCHAR(4000) IS
 DECLARE vNOME_TABELA VARCHAR(30);

vSQL           VARCHAR(256);    BEGIN
--string que recebe o comando SQL dinâmico

     vSQL := 'SELECT DISTINCT ''TABELA'' || C.CATALOGO FROM CONVENIOS C WHERE C.CONVENIO = ' || V_CONVENIO;

     EXECUTE IMMEDIATE vSQL INTO vNOME_TABELA;

     RETURN(vNOME_TABELA);

END GET_NOME_TABELA;
$$ LANGUAGE plpgsql;

