CREATE TABLE PEDIDOS 
(PEDIDO             NUMBER(6),
 DEPTO_ORIGEM       NUMBER(3),
 DEPTO_DESTINO      NUMBER(3),
 DATA_PEDIDO        DATE,
 HORA_PEDIDO        VARCHAR2(5)   NOT NULL,
 STATUS             VARCHAR2(1)   NOT NULL,
 OBSERVACAO         VARCHAR2(100),
 USUARIO            VARCHAR2(10)  NOT NULL, 
 DATA_CAD           DATE,
 USUARIO_RECEPTOR   VARCHAR2(10),
 HORA_RECEBIMENTO   VARCHAR2(5),
 DATA_RECEBIMENTO   DATE)
TABLESPACE DADOS;
