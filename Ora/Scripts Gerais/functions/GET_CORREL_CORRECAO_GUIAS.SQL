CREATE OR REPLACE FUNCTION GET_CORREL_CORRECAO_GUIAS(V_ID_ATENDIMENTO IN NUMBER) RETURN NUMBER IS RESULT NUMBER;
BEGIN
     SELECT NVL(MAX(CORREL_CORRECAO),0) INTO RESULT FROM CORRECAO_GUIAS_ATENDIMENTOS
      WHERE ID_ATENDIMENTO = V_ID_ATENDIMENTO;

    RETURN(RESULT);
END GET_CORREL_CORRECAO_GUIAS;
