CREATE OR REPLACE FUNCTION GET_MNEMONICOS(V_POSTO       IN NUMBER,
                                          V_ATENDIMENTO IN NUMBER) RETURN VARCHAR2 IS MNEMONICOS VARCHAR2(200);

    CURSOR CUR_MNEMONICOS IS
      SELECT MNEMONICO FROM EXAMES WHERE POSTO = V_POSTO AND ATENDIMENTO = V_ATENDIMENTO;

BEGIN

MNEMONICOS := '';

FOR MNEMONICOS_REC in CUR_MNEMONICOS
LOOP
    MNEMONICOS := MNEMONICOS || MNEMONICOS_REC.MNEMONICO || ' ';
END LOOP;

RETURN MNEMONICOS;

END;
