CREATE OR REPLACE FUNCTION GET_MNEMONICO_PARA_DE(V_POSTO       IN NUMBER,
                                                 V_ATENDIMENTO IN NUMBER,
                                                 V_CORREL_PARA IN NUMBER) RETURN VARCHAR2 IS MNEMONICO_CORRELACIONADO VARCHAR2(7); 
BEGIN
    SELECT E.MNEMONICO INTO MNEMONICO_CORRELACIONADO 
	  FROM EXAMES_CORRELACIONADOS EC, EXAMES E
     WHERE EC.POSTO = V_POSTO AND EC.ATENDIMENTO = V_ATENDIMENTO AND EC.CORREL_PARA = V_CORREL_PARA
	   AND E.POSTO = V_POSTO AND E.ATENDIMENTO = V_ATENDIMENTO AND E.CORREL = EC.CORREL_DE;

    RETURN MNEMONICO_CORRELACIONADO;
    
END GET_MNEMONICO_PARA_DE;
/
