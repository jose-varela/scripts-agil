CREATE OR REPLACE FUNCTION GET_USUARIO_PRIMEIRA_COLETA(V_POSTO       IN NUMBER,
                                                       V_ATENDIMENTO IN NUMBER,
                                                       V_CORREL      IN NUMBER) RETURN VARCHAR2 IS RESULT VARCHAR2(20);
BEGIN
     SELECT AM.USUARIO_COLE INTO RESULT FROM AMOSTRAS AM
      WHERE AM.POSTO = V_POSTO
        AND AM.ATENDIMENTO = V_ATENDIMENTO
        AND AM.CORREL = V_CORREL
        AND AM.AMOSTRA = 1;
    RETURN(RESULT);
END GET_USUARIO_PRIMEIRA_COLETA;
/
