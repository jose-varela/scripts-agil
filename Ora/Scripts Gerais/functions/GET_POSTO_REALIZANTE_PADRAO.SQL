CREATE OR REPLACE FUNCTION GET_POSTO_REALIZANTE_PADRAO(V_MNEMONICO   IN VARCHAR,
                                                       V_POSTO       IN NUMBER) RETURN CHAR IS RESULT CHAR;
BEGIN
     SELECT NVL(PADRAO,'N') INTO RESULT FROM POSTOS_PROCEDIMENTOS
      WHERE MNEMONICO = V_MNEMONICO
        AND POSTO = V_POSTO;

    RETURN(RESULT);
END GET_POSTO_REALIZANTE_PADRAO;
