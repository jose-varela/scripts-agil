CREATE OR REPLACE FUNCTION GET_ULTIMO_EVOLUCAO_RESULTADO(V_POSTO       IN NUMBER,
                                                         V_ATENDIMENTO IN NUMBER,
                                                         V_CORREL      IN NUMBER) RETURN DATE IS RESULT DATE;
BEGIN
     SELECT MAX(ER.DATA_EVOLUCAO) INTO RESULT FROM EVOLUCAO_RESULTADOS ER
      WHERE ER.POSTO = V_POSTO
        AND ER.ATENDIMENTO = V_ATENDIMENTO
        AND ER.CORREL = V_CORREL;
    RETURN(RESULT);
END GET_ULTIMO_EVOLUCAO_RESULTADO;
/
