CREATE OR REPLACE FUNCTION IS_WORKLIST_RESULTADO(V_POSTO       IN NUMBER,
                                                 V_ATENDIMENTO IN NUMBER,
                                                 V_CORREL      IN NUMBER) RETURN NUMBER IS QT_RESULTADOS NUMBER; 
BEGIN
    SELECT COUNT(1) INTO QT_RESULTADOS FROM WORKLIST_RESULTADOS
     WHERE POSTO = V_POSTO AND ATENDIMENTO = V_ATENDIMENTO AND CORREL = V_CORREL;

    RETURN QT_RESULTADOS;
END IS_WORKLIST_RESULTADO;                                      
/

