CREATE OR REPLACE FUNCTION GET_NOME_TABELA(V_CONVENIO IN NUMBER) RETURN VARCHAR2 IS vNOME_TABELA VARCHAR2(30);

vSQL           VARCHAR2(256);    --string que recebe o comando SQL dinâmico

BEGIN
     vSQL := 'SELECT DISTINCT ''TABELA'' || C.CATALOGO FROM CONVENIOS C WHERE C.CONVENIO = ' || V_CONVENIO;

     EXECUTE IMMEDIATE vSQL INTO vNOME_TABELA;

     RETURN(vNOME_TABELA);

END GET_NOME_TABELA;

