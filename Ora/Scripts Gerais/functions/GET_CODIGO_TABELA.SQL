CREATE OR REPLACE FUNCTION GET_CODIGO_TABELA(V_CONVENIO    IN NUMBER,
                                             V_MNEMONICO   IN VARCHAR2) RETURN VARCHAR2 IS vCODIGO_TABELA VARCHAR2(10);
vNOME_TABELA VARCHAR2(30);
vSQL         VARCHAR2(256);    --string que recebe o comando SQL dinâmico

BEGIN
     vSQL := 'SELECT DISTINCT ''TABELA'' || C.CATALOGO FROM CONVENIOS C WHERE C.CONVENIO = ' || V_CONVENIO;

     EXECUTE IMMEDIATE vSQL INTO vNOME_TABELA;

     vSQL := 'SELECT CODIGO FROM '|| vNOME_TABELA || ' WHERE MNEMONICO = ''' || V_MNEMONICO || '''';
	 
     EXECUTE IMMEDIATE vSQL INTO vCODIGO_TABELA;
	 
     RETURN(vCODIGO_TABELA);

END GET_CODIGO_TABELA;
