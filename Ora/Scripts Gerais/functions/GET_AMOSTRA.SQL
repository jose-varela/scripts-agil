CREATE OR REPLACE FUNCTION GET_AMOSTRA(V_POSTO       IN NUMBER,
                                       V_ATENDIMENTO IN NUMBER,
                                       V_CORREL      IN NUMBER) RETURN NUMBER IS RESULT NUMBER;
BEGIN
     SELECT NVL(MAX(AMOSTRA),0) INTO RESULT FROM AMOSTRAS
      WHERE POSTO = V_POSTO 
        AND ATENDIMENTO = V_ATENDIMENTO 
        AND CORREL = V_CORREL;

    RETURN(RESULT);
END GET_AMOSTRA;
/
