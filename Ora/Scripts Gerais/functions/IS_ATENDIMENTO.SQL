CREATE OR REPLACE FUNCTION IS_ATENDIMENTO(V_POSTO       IN NUMBER,
                                          V_ATENDIMENTO IN NUMBER) RETURN BOOLEAN IS QT_ATENDIMENTOS NUMBER; 
BEGIN
    SELECT COUNT(1) INTO QT_ATENDIMENTOS FROM ATENDIMENTOS
     WHERE POSTO = V_POSTO AND ATENDIMENTO = V_ATENDIMENTO;

    IF QT_ATENDIMENTOS = 0 THEN
       RETURN FALSE;
    ELSE
       RETURN TRUE;
    END IF;
END IS_ATENDIMENTO;                                      
/

