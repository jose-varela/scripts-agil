CREATE OR REPLACE FUNCTION GET_MAX_ORDEM_CORRELACAO(V_POSTO       IN NUMBER,
                                                    V_ATENDIMENTO IN NUMBER) RETURN NUMBER IS RESULT NUMBER;
BEGIN
     SELECT NVL(MAX(EC.ORDEM_CORRELACAO),0) INTO RESULT FROM EXAMES_CORRELACIONADOS EC
      WHERE EC.POSTO = V_POSTO
        AND EC.ATENDIMENTO = V_ATENDIMENTO;
    RETURN(RESULT);
END GET_MAX_ORDEM_CORRELACAO;
/

