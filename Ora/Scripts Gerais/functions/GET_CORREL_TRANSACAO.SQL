CREATE OR REPLACE FUNCTION GET_CORREL_TRANSACAO(V_POSTO       IN NUMBER,
                                                V_ATENDIMENTO IN NUMBER) RETURN NUMBER IS RESULT NUMBER;
BEGIN
     SELECT NVL(MAX(CORREL_TRANSACAO),0) INTO RESULT FROM TRANSACOES_TES
      WHERE POSTO = V_POSTO 
        AND ATENDIMENTO = V_ATENDIMENTO;

    RETURN(RESULT);
END GET_CORREL_TRANSACAO;
