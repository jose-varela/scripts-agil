CREATE OR REPLACE FUNCTION IS_EXAME_CORRELACIONADO_PARA(V_POSTO       IN NUMBER,
                                                        V_ATENDIMENTO IN NUMBER,
                                                        V_CORREL_PARA IN NUMBER) RETURN VARCHAR2 IS QT_EXAMES_CORRELACIONADOS NUMBER; 
BEGIN
    SELECT COUNT(1) INTO QT_EXAMES_CORRELACIONADOS FROM EXAMES_CORRELACIONADOS
     WHERE POSTO = V_POSTO AND ATENDIMENTO = V_ATENDIMENTO AND CORREL_PARA = V_CORREL_PARA;

    IF QT_EXAMES_CORRELACIONADOS = 0 THEN
       RETURN 'Z';
    ELSE
       RETURN 'A';
    END IF;
END IS_EXAME_CORRELACIONADO_PARA;                                      
/
